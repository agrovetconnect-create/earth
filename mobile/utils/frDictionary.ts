function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : `{${key}}`
  );
}

export function lookupMobileFrench(
  raw: string,
  vars?: Record<string, string | number>
): string {
  if (!raw) return raw;

  const exact = MOBILE_FR_DICTIONARY[raw];
  if (exact !== undefined) return interpolate(exact, vars);

  const trimmed = raw.trim();
  if (!trimmed) return raw;

  const leading = raw.slice(0, raw.indexOf(trimmed));
  const trailing = raw.slice(raw.indexOf(trimmed) + trimmed.length);

  if (MOBILE_FR_DICTIONARY[trimmed] !== undefined) {
    return `${leading}${interpolate(MOBILE_FR_DICTIONARY[trimmed], vars)}${trailing}`;
  }

  const lower = trimmed.toLowerCase();
  if (MOBILE_FR_ENUM_DICTIONARY[lower] !== undefined) {
    const mapped = MOBILE_FR_ENUM_DICTIONARY[lower];
    const capitalized =
      trimmed[0] && trimmed[0] === trimmed[0].toUpperCase() && trimmed[0] !== trimmed[0].toLowerCase()
        ? mapped.charAt(0).toUpperCase() + mapped.slice(1)
        : mapped;
    return `${leading}${interpolate(capitalized, vars)}${trailing}`;
  }

  if (trimmed.includes(' · ')) {
    const parts = trimmed.split(' · ');
    let changed = false;
    const translatedParts = parts.map((part) => {
      const next = lookupMobileFrench(part, vars);
      if (next !== part) changed = true;
      return next;
    });
    if (changed) {
      return `${leading}${translatedParts.join(' · ')}${trailing}`;
    }
  }

  for (const [pattern, replacer] of MOBILE_FR_PATTERNS) {
    const match = trimmed.match(pattern);
    if (match) {
      return `${leading}${interpolate(replacer(...match.slice(1)), vars)}${trailing}`;
    }
  }

  return interpolate(raw, vars);
}
